<template>
  <article>
    <h1>设计价值观</h1>
    <p class="i-lead">
      设计体系不是组件的集合，而是一组被反复验证的决策。以下三条价值观决定了 Ignorance Design
      里每一个默认值的取舍，也是评审新组件是否合格的标尺。
    </p>

    <h2>沉浸 Immersive</h2>
    <p>
      中后台产品的使用时长以小时计。界面的职责是承载信息，而不是争夺注意力。因此我们把强饱和色
      严格限制在"需要用户行动"的位置：主按钮、当前选中项、错误提示。其余区域一律使用中性灰阶。
    </p>
    <ul>
      <li>一屏之内主色出现不超过一次，否则用户无法判断该点哪里。</li>
      <li>分割优先用留白，其次用浅色描边，最后才考虑阴影。</li>
      <li>动效时长不超过 320ms，只用于解释空间关系，不做装饰。</li>
    </ul>

    <h2>灵活 Flexible</h2>
    <p>
      组件样式全部引用语义令牌（<code>--i-color-brand</code> 而非 <code>#5e7ce0</code>），
      主题切换、业务换肤、深色模式因此只需覆盖语义层，组件代码零改动。
    </p>
    <ul>
      <li>基础层（调色板、刻度）只描述值，语义层描述用途，组件只消费语义层。</li>
      <li>任何组件不得出现硬编码色值、字号或间距。</li>
      <li>尺寸沿用统一的 <code>sm / md / lg</code> 三档，避免每个组件自造一套。</li>
    </ul>

    <h2>至简 Minimal</h2>
    <p>
      每多一个 prop，就多一次使用者需要做的决策。我们的做法是：默认值即最佳实践，
      只有当"两种选择都足够常见"时才开放配置。
    </p>
    <ul>
      <li>新增 API 前先问：能否用已有组件组合实现？</li>
      <li>布尔 prop 的默认值一律为 <code>false</code>，避免隐式行为。</li>
      <li>组件不内置业务文案，一切可变内容通过插槽传入。</li>
    </ul>

    <h2>无障碍是底线，不是可选项</h2>
    <p>
      上述三条价值观之外，可访问性不参与权衡：语义化标签、键盘可达、可见的焦点样式与正确的
      ARIA 状态是组件合入的前置条件。
    </p>
  </article>
</template>

